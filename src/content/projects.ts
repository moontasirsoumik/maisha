function plate(
  slug: string,
  id: string,
  alt: string,
  caption: string,
  kind: Plate['kind'],
): Plate {
  const size = sizes[`${slug}/${id}`];
  return {
    id,
    src: `/work/${slug}/${id}.webp`,
    full: `/work/${slug}/${id}-full.webp`,
    width: size.width,
    height: size.height,
    alt,
    caption,
    kind,
  };
}

